function add(a, b) {
  return a + b;
}

function divide(a, b) {
  return a / b;
}

function mulitply(a, b) {
  return a * b;
}

function subtract(a, b) {
  return a - b;
}

function findMax(a, b) {
  return Math.max(a, b);
}

function squareRoot(num) {
  return Math.sqrt(num);
}

module.exports = {
  add,
  divide,
  mulitply,
  subtract,
  findMax,
  squareRoot,
};
